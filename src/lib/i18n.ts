const DICTS: Record<Lang, Copy> = { en, ar, de, fr, es, it };

export type CopyKey = keyof typeof en;

const NAMES: Record<Lang, string> = { en: 'English', ar: 'العربية', de: 'Deutsch', fr: 'Français', es: 'Español', it: 'Italiano' };

/** English names keep the AI instruction unambiguous. */
const AI_NAMES: Record<Lang, string> = {
  en: 'English',
  ar: 'Arabic (العربية), written right-to-left',
  de: 'German (Deutsch)',
  fr: 'French (Français)',
  es: 'Spanish (Español)',
  it: 'Italian (Italiano)',
};

function isLang(value: unknown): value is Lang {
  return typeof value === 'string' && (LANGS as readonly string[]).includes(value);
}

export function readLang(): Lang {
  if (typeof window === 'undefined') return 'en';
  const raw = window.localStorage.getItem(LANG_KEY);
  return isLang(raw) ? raw : 'en';
}

export function writeLang(lang: Lang) {
  window.localStorage.setItem(LANG_KEY, lang);
}

export function translate(lang: Lang, key: CopyKey, vars?: Record<string, string | number>) {
  const text = DICTS[lang][key] || en[key];
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

export function languageName(lang: Lang) {
  return NAMES[lang];
}

export function aiLanguageName(lang: Lang) {
  return AI_NAMES[lang];
}

export function isRtl(lang: Lang) {
  return lang === 'ar';
}

/** Flips the document direction so Arabic reads right-to-left and every other language left-to-right. */
export function applyDocumentLanguage(lang: Lang) {
  if (typeof document === 'undefined') return;
  const root = document.documentElement;
  root.dir = isRtl(lang) ? 'rtl' : 'ltr';
  root.lang = lang;
}
