const DICTS = { en, de, fr, es, it };

export type CopyKey = keyof typeof en;

export function readLang(): Lang {
  if (typeof window === 'undefined') return 'en';
  const raw = window.localStorage.getItem(LANG_KEY);
  return raw === 'de' || raw === 'fr' || raw === 'es' || raw === 'it' ? raw : 'en';
}

export function writeLang(lang: Lang) {
  window.localStorage.setItem(LANG_KEY, lang);
}

export function translate(lang: Lang, key: CopyKey) {
  return DICTS[lang][key] || en[key];
}

export function languageName(lang: Lang) {
  return { en: 'English', de: 'Deutsch', fr: 'Français', es: 'Español', it: 'Italiano' }[lang];
}

